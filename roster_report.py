# -*- coding: utf-8 -*-
# ★ 小项目：花名册 SQL 版结构报告


import os
import sqlite3
import pandas as pd

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DB = os.path.join(BASE, "_假数据", "roster.db")
conn = sqlite3.connect(DB)


def 跑(sql, 说明=""):
    print(f"\n{'='*56}\n【{说明}】\n{'='*56}")
    df = pd.read_sql(sql, conn)
    print(df.to_string(index=False))
    return df


# ---------------------------------------------------------------
# 任务 1：全公司有多少人？1 个数字
# 提示：数行数用 COUNT(*)
# ---------------------------------------------------------------
跑("""
SELECT COUNT(*) AS 总人数 FROM employees
""", "任务1 · 总人数")


# ---------------------------------------------------------------
# 任务 2：平均年龄、平均司龄，各保留 1 位小数
# 提示：AVG(列) 求平均，ROUND(x,1) 保留 1 位小数
# 期待输出两列：平均年龄 33.0 / 平均司龄 8.0
# ---------------------------------------------------------------
跑("""
SELECT ROUND(AVG(年龄),1) AS 平均年龄, ROUND(AVG(司龄),1) AS 平均司龄 
FROM employees
""","任务2·平均年龄·平均司龄")


# ---------------------------------------------------------------
# 任务 3：只统计在职的人，一共几个？
# 提示：筛选条件 WHERE 在职状态 = '在职'（字符串要带单引号）
# 答案：18
# ---------------------------------------------------------------
跑("""
SELECT COUNT(*) AS 在职人数 FROM employees WHERE 在职状态='在职'
""", "任务3 · 在职人数")


# ---------------------------------------------------------------
# 任务 4：每个部门多少人？按人数从多到少排
# 提示：GROUP BY 部门 + COUNT(*)，再 ORDER BY ... DESC
# 期待：5 个部门，每个部门 4 人
# ---------------------------------------------------------------
跑("""
SELECT 部门, COUNT(*) AS 人数 FROM employees
GROUP BY 部门 ORDER BY 人数 DESC 
""", "任务4 · 各部门人数")


# ---------------------------------------------------------------
# 任务 5：每种学历各多少人？
# 期待：本科 12 / 硕士 4 / 博士 4
# ---------------------------------------------------------------
跑("""
SELECT 学历, COUNT(*) AS 人数 FROM employees
GROUP BY 学历 ORDER BY 人数 DESC
""", "任务5 · 学历分布")


# ---------------------------------------------------------------
# 任务 6：司龄最大的 3 个人是谁？（昨天你刚学的）
# 期待：员工14 / 员工04 / 员工19
# ---------------------------------------------------------------
跑("""
SELECT 姓名, 司龄 FROM employees
ORDER BY 司龄 DESC LIMIT 3
""", "任务6 · 司龄 Top3")





